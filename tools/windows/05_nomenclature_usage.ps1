# Какая номенклатура реально используется в нарядах за последние N дней:
# код, наименование, сколько раз встречалась и разброс цен - отдельно по
# вкладкам Услуги / Склад (Товары) / Услуги прочих организаций.
#
# Это замена ручному catalog.json: бот будет сопоставлять распознанные
# позиции с реальными элементами справочника 1С. Только чтение, без
# персональных данных.

$days = 90

$r = @()
try {
  Connect-1C
  $text = @"
ВЫБРАТЬ "Услуги" КАК ТЧ, Т.Номенклатура КАК Ном, Т.Номенклатура.Код КАК Код,
  КОЛИЧЕСТВО(*) КАК Раз, МИНИМУМ(Т.Цена) КАК ЦенаМин, МАКСИМУМ(Т.Цена) КАК ЦенаМакс
ИЗ Документ.ЗаказПокупателя.Услуги КАК Т
ГДЕ Т.Ссылка.Дата >= &Дата И Т.Ссылка.Проведен
СГРУППИРОВАТЬ ПО Т.Номенклатура, Т.Номенклатура.Код
ОБЪЕДИНИТЬ ВСЕ
ВЫБРАТЬ "Склад", Т.Номенклатура, Т.Номенклатура.Код,
  КОЛИЧЕСТВО(*), МИНИМУМ(Т.Цена), МАКСИМУМ(Т.Цена)
ИЗ Документ.ЗаказПокупателя.Товары КАК Т
ГДЕ Т.Ссылка.Дата >= &Дата И Т.Ссылка.Проведен
СГРУППИРОВАТЬ ПО Т.Номенклатура, Т.Номенклатура.Код
ОБЪЕДИНИТЬ ВСЕ
ВЫБРАТЬ "Прочие", Т.Услуга, Т.Услуга.Код,
  КОЛИЧЕСТВО(*), МИНИМУМ(Т.Сумма), МАКСИМУМ(Т.Сумма)
ИЗ Документ.ЗаказПокупателя.УслугиПрочихОрганизаций КАК Т
ГДЕ Т.Ссылка.Дата >= &Дата И Т.Ссылка.Проведен
СГРУППИРОВАТЬ ПО Т.Услуга, Т.Услуга.Код
УПОРЯДОЧИТЬ ПО ТЧ, Раз УБЫВ
"@
  $sel = Query1C $text @{ "Дата" = (Get-Date).Date.AddDays(-$days) }
  $r += "Номенклатура в проведённых нарядах за $days дней (вкладка | код | наименование | раз | цена мин-макс)"
  $tab = ""
  while (Next1C $sel) {
    $t = P1C $sel "ТЧ"
    if ($t -ne $tab) { $r += ""; $r += "=== $t ==="; $tab = $t }
    $r += "$t | " + (P1C $sel "Код") + " | " + (T1C (P1C $sel "Ном")) + " | " + (P1C $sel "Раз") + " | " + (P1C $sel "ЦенаМин") + "-" + (P1C $sel "ЦенаМакс")
  }
} catch {
  $r += Format-Error1C $_
} finally {
  $sel = $null
  Disconnect-1C
}
Save-Result "05-nomenclature-usage" $r
