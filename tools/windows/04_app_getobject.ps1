# Проверка: работает ли ПолучитьОбъект() наряда через V83.Application
# (скрытый толстый клиент, клиентский контекст). Через V83.COMConnector
# модуль объекта наряда не компилируется (РежимДиалогаВопрос), а для
# записи нарядов кодом нужен именно объект.
#
# Только чтение: объект загружается в память и не записывается.

$r = @()
try {
  Connect-1CApp
  $sel = Query1C "ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка, Номер ИЗ Документ.ЗаказПокупателя ГДЕ Проведен И НЕ ПометкаУдаления И НЕ Отменен УПОРЯДОЧИТЬ ПО Дата УБЫВ"
  if (-not (Next1C $sel)) { throw "Не найдено ни одного проведённого наряда" }
  $ref = P1C $sel "Ссылка"
  $num = P1C $sel "Номер"
  $r += "Последний наряд: $num"

  $o = M1C $ref "GetObject|ПолучитьОбъект" @()
  $r += "ПолучитьОбъект через толстый клиент: OK"
  foreach ($tsn in "Услуги", "Товары", "УслугиПрочихОрганизаций", "Расчеты", "ТочкиМаршрута", "ИсполнителиРабот") {
    $r += "  [$tsn] строк: " + @(Items1C (SP1C $o $tsn)).Count
  }
} catch {
  $r += Format-Error1C $_
} finally {
  $o = $null; $ref = $null; $sel = $null
  Disconnect-1CApp
}
Save-Result "04-app-getobject" $r
